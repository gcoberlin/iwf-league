  content:`> **69, 57, 45 – und dann wurde es still.** Nach dem lauten Saisonauftakt war die IWF-Gruppe in dieser Woche beinahe verdächtig ruhig. Auf dem Transfermarkt dagegen wurde gearbeitet. Teilweise sogar sinnvoll.

Nach Spieltag eins führt **José mit 69 Punkten** vor Luca (57) und Greg (45). Sebastian folgt mit 41, Wassili mit 31, Tomi mit 26, Jan mit 24, Henning mit 21 und Matze mit fünf Punkten. Uwe steht nach der nicht abgegebenen Aufstellung bei null.

Die Redaktion hat deshalb vor Spieltag zwei nicht nur auf Marktwerte geschaut, sondern auf Rollen, Startelfchancen, Verletzungen und das tatsächliche Punktepotenzial.

## José: Der Spitzenreiter lässt den Kern stehen

Kane, Suzuki, Gutiérrez, Ginter und Tietz bleiben das Gerüst. Nach dem 69-Punkte-Auftakt musste José nicht hektisch werden. Nadir ging, Schäfer und Klaas kamen günstig dazu.

Die wichtigste Erkenntnis aus Spieltag eins bleibt ohnehin: **Kane musste José gar nicht retten. Suzuki tat es.**

**Werner:** „Das ist die angenehmste Form von Luxus. 69 Punkte holen und danach nicht glauben, man müsse den halben Kader austauschen.“

## Luca: 7,777 Millionen für eine ziemlich interessante Wette

Luca hat Hack und Aséko verkauft und **Ebnoutalib für 7,777 Mio. €** geholt. Das ist einer der interessantesten Käufe der Woche: LigaInsider sieht ihn im Frankfurter Konkurrenzkampf mit realer Startelfchance. Dazu kam Mitchell Weiser für 2,2 Mio. € – deutlich spekulativer, weil er nach langer Pause erst wieder an den Spieltagskader herangeführt wird.

Kimmich bleibt der Fixpunkt. Ebnoutalib könnte aber genau die offensive Decke liefern, die dem Kader noch gefehlt hat.

**Ingo:** „Das ist kein billiger Kauf. Aber einer mit Idee.“

## Sebastian: Laptop wieder aufgeklappt

74,86 Mio. € Kaderwert, 41 Punkte zum Start – und selbstverständlich war das für den Laptoptrainer kein Grund, die Finger stillzuhalten. Assignon, Lukeba, Tiago Tomás und zuletzt Doué kamen dazu.

Der Haken: **Tiago Tomás wird aktuell mit einer Muskelverletzung geführt.** Der Einkauf ist damit kurzfristig eher Warteposition als Soforthilfe. Dafür ist Sebastians Kader inzwischen so breit, dass er Ausfälle besser auffangen kann als fast jeder andere.

**Franz:** „Andere schließen nach dem Transferfenster den Laptop. Häjne lädt nur das Netzteil.“

## Greg: 45 Punkte, Grüll – und dann Pisa

Der Dino ist nach dem Auftakt plötzlich Dritter. Jetzt kam **Marco Grüll für 3,698 Mio. €** dazu. LigaInsider sieht Grüll im Bremer Rennen um die Startelf aktuell mit guten Karten – für den Preis ein nachvollziehbarer Versuch.

Gregor selbst weilt derweil in **Pisa**. Nach 45 Punkten darf man sich offenbar auch einmal persönlich davon überzeugen, ob ein schiefer Start zwingend schlecht sein muss.

**Franz:** „Der Dino kontrolliert den Schiefen Turm. Uwe kontrolliert hoffentlich diesmal seine Aufstellung.“

## Henning: Umbau statt Feintuning

Niemand hat diese Woche konsequenter umgebaut. **Karaman, Larsson, Poku und Ayhan raus; Scherhant, Shkiri und Jeltsch rein.** Besonders Jeltsch bringt eine interessante Perspektive mit und gehört beim VfB zum ernsthaften Startelfkreis.

Das ist mutiger als bloßes Nachjustieren. Ob es besser ist, muss Spieltag zwei zeigen. Guirassy und Burkardt bleiben jedenfalls die beiden Spieler, an denen Hennings Saison hängt.

**Werner:** „Viel Bewegung ist noch keine Verbesserung. Aber hier erkenne ich zumindest einen Plan.“

## Matze: Nach fünf Punkten kommt Rômulo

Fünf Punkte waren der Fehlstart der Woche. Matze reagierte und holte **Rômulo für 5,77 Mio. €**. Das Potenzial ist offensichtlich, die Soforthilfe weniger: Der Leipziger befindet sich nach seinen Problemen erst auf dem Weg zurück ins Mannschaftstraining.

Damit bleibt Matze das vielleicht größte Projekt der Liga: viel Talent, viel Kader, viel Upside – und jetzt bitte auch Punkte.

**Franz:** „Fünf Punkte und anschließend einen Spieler im Aufbautraining kaufen. Der Pumper glaubt weiter an langfristigen Muskelaufbau.“

## Jan, Tomi und Vasco: erstaunlich wenig Aktionismus

Jan vertraut nach 24 Punkten weiter auf Undav, Tillman, Baku und Laimer. Tomi lässt seinen Kader nach 26 Punkten ebenfalls weitgehend stehen. Und **Dino-Coach Vasco** kommt mit Olise und 31 Punkten aus einem ordentlichen Auftakt – ohne die Reiseleitung für Rom aus den Augen zu verlieren.

Während Greg in Pisa bereits italienische Platzverhältnisse prüft, hat Vasco die eigentliche IWF-Auswärtsplanung ohnehin längst im Griff.

## Und Uwe?

Uwe stellte am ersten Spieltag nicht auf. Ergebnis: **0 Punkte.**

Die logische Reaktion auf einen solchen Fehlstart wäre Aktivität gewesen. Transfers. Umbau. Irgendein Lebenszeichen.

Die sichtbare Transferbilanz dieser Woche: **kein Einkauf.**

**Ingo:** „Bei Uwe ist die wichtigste Personalie weiterhin Uwe.“

**Franz:** „Wir wollten den Transfer der Woche bewerten. Uwe hat sich aus Gründen der Neutralität nicht beteiligt.“

## Vor Spieltag zwei ist noch gar nichts entschieden

José startet als Spitzenreiter, Luca hat nachgelegt, Greg kommt mit Rückenwind zurück aus Pisa und Sebastian besitzt weiterhin einen der tiefsten Kader der Liga. Henning hat aggressiv umgebaut, Matze muss reagieren und Uwe muss zunächst einmal elf Spieler aufstellen.

Ein Spieltag ist keine Saison. Aber ab dem zweiten Wochenende gibt es immerhin keine Ausrede mehr, man habe noch keine Daten.

**Werner:** „Jetzt beginnt die interessante Phase. Der erste Spieltag kann Zufall sein. Ab jetzt sehen wir Muster.“

**Franz:** „Außer bei Uwe. Da wären elf grüne Häkchen schon ein Muster.“`
